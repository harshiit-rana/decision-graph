"""The mechanical arm of the agent study's task set, taken whole by a recorded procedure (#140).

Pre-registration: this script and its output are committed BEFORE any agent runs. It reads
GitHub only, through the `gh` CLI. It never touches the graph and never calls a model.

    python eval/agent_study/select_tasks.py fetch    # writes pool.json, the exact input
    python eval/agent_study/select_tasks.py draw     # writes draw.json from pool.json

The two steps are separate so that the INPUT is a committed file. Anyone can re-run `draw` on
the committed pool.json and must get the committed draw.json, whatever GitHub holds by then.
`fetch` is for auditing the pool against GitHub, and its output will drift as issues are edited.

What a task is. A *precedent task*: an issue that a maintainer closed by pointing at an earlier
artifact in the same repository ("this was already discussed in #N"). The history that decides
how the issue should be handled is in that earlier artifact and not in the issue's text.

Eligibility (fixed before looking at the result). An issue or pull request is in the pool when
ALL hold:
- it was created within that repository's task window (TASK_WINDOWS), a window strictly inside
  what an ingestion by 2026-11-01 covers, so a few days' delay can't move a task outside it;
- GitHub reports it closed (merged, unmerged, completed, not planned or duplicate: the reason is
  recorded and is not a filter);
- a comment by a maintainer (author association OWNER, MEMBER or COLLABORATOR) links an issue or
  pull request of the same repository by `#N` or URL;
- at least one linked artifact is not the issue itself, has a lower number, and was created inside
  the same window, at least MIN_GAP_DAYS before the first maintainer comment that links it, the
  DECISION POINT. (The graph can only hold what is in its window, and an artifact opened the same
  day is not "earlier history". The agent in the study may know only what existed just before the
  decision point.);
- not every such precedent was already merged before the decision point. A merged change is in the
  repository checkout, which an agent with repository access alone can read, so the item would not
  test recorded history. (A precedent that was open, or closed unmerged, exists only on GitHub.)
Issues whose author is a bot, and issues a maintainer marked as machine-generated, stay in the
pool and are COUNTED, because dropping them by reading their text would be a judgement made after
looking. The exclusion that does apply is mechanical and stated in `exclusions`: a maintainer
comment containing one of JUNK_MARKERS ("AI junk", "spam", ...) removes the issue, since a task
whose ground truth is "this was spam" tests nothing about history.

The first version of this rule was narrower (issues closed as not planned or duplicate only) and
found 2 eligible items across both repositories. That was too few to study, so the rule was widened
to pull requests and to any closure reason BEFORE any ground truth was written, and the narrow
result is disclosed here. The widened rule finds few enough items that all of them are taken: there
is no random draw, because sampling 12 from 16 would add a source of variation and no protection
against a bias this procedure does not have.

The unit of a task is the PRECEDENT, not the later item. Several pull requests re-propose the same
declined change (for example four PRs on `allowed_methods`), and treating them as separate tasks
would count one piece of history four times. Items that share a precedent are one cluster, and the
task is the cluster's earliest item.
"""

from __future__ import annotations

import json
import random
import re
import subprocess
import sys
from datetime import date
from pathlib import Path

HERE = Path(__file__).parent
MIN_GAP_DAYS = 3
MAINTAINER = {"OWNER", "MEMBER", "COLLABORATOR"}
JUNK_MARKERS = ("ai junk", "ai spam", "llm junk", "spam", "ai-generated", "generated by ai",
                "use ai to generate", "ai code scanner", "ai slop")

# repo -> (first created, last created). Tasks need their earlier artifact in the graph window, so
# the lower bound sits after the window floor of an ingestion by 2026-11-01.
TASK_WINDOWS = {
    "pallets/flask": ("2025-08-20", "2026-08-10"),
    "urllib3/urllib3": ("2025-11-01", "2026-09-30"),
}

QUERY = """
query($q: String!, $after: String) {
  search(query: $q, type: ISSUE, first: 25, after: $after) {
    issueCount
    pageInfo { hasNextPage endCursor }
    nodes {
      ... on Issue {
        number title url createdAt closedAt stateReason
        author { login __typename }
        body
        comments(first: 40) { nodes { author { login __typename } authorAssociation createdAt body url } }
      }
      ... on PullRequest {
        number title url createdAt closedAt merged
        author { login __typename }
        body
        comments(first: 40) { nodes { author { login __typename } authorAssociation createdAt body url } }
      }
    }
  }
}
"""


def gh_graphql(query: str, **variables: str) -> dict:
    args = ["gh", "api", "graphql", "-f", f"query={query}"]
    for k, v in variables.items():
        if v is not None:
            args += ["-f", f"{k}={v}"]
    out = subprocess.run(args, check=True, capture_output=True, text=True, encoding="utf-8")
    return json.loads(out.stdout)["data"]


def fetch_repo(repo: str, lo: str, hi: str) -> list[dict]:
    found: dict[int, dict] = {}
    # Month by month: a search returns at most 1000 results, and a busy month stays under it.
    for a, b in months(lo, hi):
        q = f"repo:{repo} is:closed created:{a}..{b}"
        after = None
        while True:
            data = gh_graphql(QUERY, q=q, after=after)["search"]
            for n in data["nodes"]:
                if n:
                    found[n["number"]] = n
            if not data["pageInfo"]["hasNextPage"]:
                break
            after = data["pageInfo"]["endCursor"]
    return [found[k] for k in sorted(found)]


def months(lo: str, hi: str) -> list[tuple[str, str]]:
    """Calendar-month slices of [lo, hi], as inclusive date strings."""
    out, d, end = [], date.fromisoformat(lo), date.fromisoformat(hi)
    while d <= end:
        nxt = date(d.year + (d.month == 12), d.month % 12 + 1, 1)
        out.append((d.isoformat(), min(end, date.fromordinal(nxt.toordinal() - 1)).isoformat()))
        d = nxt
    return out


def links_in(text: str, repo: str) -> set[int]:
    """Issue and PR numbers of `repo` that `text` links, by #N or by URL."""
    out = {int(m) for m in re.findall(r"(?<![\w/&])#(\d+)\b", text)}
    out |= {int(m) for m in re.findall(
        rf"github\.com/{re.escape(repo)}/(?:issues|pull)/(\d+)", text, flags=re.I)}
    return out


def info_of(repo: str, number: int, cache: dict) -> dict | None:
    """When #number of repo was created, closed and (for a pull request) merged, or None when it
    doesn't exist (a stray '#12'). Timestamps are kept whole: the decision point is compared to
    them to the second."""
    key = f"{repo}#{number}"
    if key not in cache:
        r = subprocess.run(
            ["gh", "api", f"repos/{repo}/issues/{number}", "--jq",
             "{created: .created_at, closed: .closed_at, merged: .pull_request.merged_at, "
             "is_pr: (.pull_request != null), state: .state}"],
            capture_output=True, text=True, encoding="utf-8")
        cache[key] = json.loads(r.stdout) if r.returncode == 0 and r.stdout.strip() else None
    return cache[key]


def judge(issue: dict, repo: str, lo: str, linked_info: dict) -> dict:
    """Classify one fetched issue. A pure function of the pool: the lookups of linked artifacts
    are made by `fetch` and stored in the pool, so `draw` needs no network."""
    maint = [c for c in issue["comments"]["nodes"] if c["authorAssociation"] in MAINTAINER]
    verdict = {"number": issue["number"], "eligible": False, "reason": None, "precedents": []}
    junk = [c["url"] for c in maint if any(m in c["body"].lower() for m in JUNK_MARKERS)]
    if junk:
        verdict["reason"] = "maintainer comment marks it junk/spam/machine-generated"
        return verdict
    linked: set[int] = set()
    for c in maint:
        linked |= links_in(c["body"], repo)
    linked.discard(issue["number"])
    for n in sorted(linked):
        if n >= issue["number"]:
            continue
        info = linked_info.get(f"{repo}#{n}")
        if not info or info["created"][:10] < lo:
            continue
        when = info["created"][:10]
        # The decision point is the first maintainer comment that links the precedent. What the
        # agent may know is what existed just before it, so the earlier artifact must be at least
        # MIN_GAP_DAYS older than THAT comment, not than the item (a maintainer can link an
        # artifact that was merged after the item was opened).
        first = min((c for c in maint if n in links_in(c["body"], repo)), key=lambda c: c["createdAt"])
        gap = (date.fromisoformat(first["createdAt"][:10]) - date.fromisoformat(when)).days
        if gap >= MIN_GAP_DAYS:
            # Merged before the decision point means its effect is in the checkout at that time,
            # so an agent with repository access alone can see it and the task would not test
            # recorded history. ISO-8601 UTC strings compare correctly as strings.
            visible = bool(info["merged"]) and info["merged"] < first["createdAt"]
            verdict["precedents"].append({
                "number": n, "created": when, "days_before_decision_point": gap,
                "decision_point": {"at": first["createdAt"], "url": first["url"]},
                "is_pr": info["is_pr"], "merged_at": info["merged"], "closed_at": info["closed"],
                "merged_before_decision_point": visible,
            })
    if not maint:
        verdict["reason"] = "no maintainer comment"
    elif not linked:
        verdict["reason"] = "no maintainer comment links an artifact"
    elif not verdict["precedents"]:
        verdict["reason"] = "linked artifacts are not earlier, in-window history"
    elif all(pr["merged_before_decision_point"] for pr in verdict["precedents"]):
        verdict["reason"] = "every precedent was merged before the decision point, so it is in the checkout"
    else:
        verdict["eligible"] = True
    return verdict


def clusters(eligible: list[dict]) -> list[dict]:
    """Group eligible items that share any precedent, as connected components, earliest item first.

    Each cluster is one piece of history re-proposed, however many times. The task is the earliest
    item; the others are recorded so a reader sees the repetition and so none is used twice.
    """
    parent: dict[int, int] = {}

    def find(x: int) -> int:
        parent.setdefault(x, x)
        while parent[x] != x:
            parent[x] = parent[parent[x]]
            x = parent[x]
        return x

    for v in eligible:
        for pr in v["precedents"]:
            parent[find(v["number"])] = find(-pr["number"])  # negative: a precedent, not an item
    groups: dict[int, list[dict]] = {}
    for v in eligible:
        groups.setdefault(find(v["number"]), []).append(v)
    out = []
    for members in groups.values():
        members.sort(key=lambda v: v["number"])
        out.append({
            "task_item": members[0]["number"],
            "also_reproposed_in": [m["number"] for m in members[1:]],
            "precedents": sorted({p["number"] for m in members for p in m["precedents"]}),
        })
    return sorted(out, key=lambda c: c["task_item"])


def draw(pool: dict) -> dict:
    """The census, as a pure function of the committed pool, so a test can reproduce it."""
    out: dict = {"procedure": "every eligible item, grouped into clusters by shared precedent; "
                              "the task is each cluster's earliest item. No sampling.",
                 "repos": {}}
    for repo, (lo, hi) in TASK_WINDOWS.items():
        p = pool["repos"][repo]
        eligible = [v for v in p["verdicts"] if v["eligible"]]
        out["repos"][repo] = {
            "window": [lo, hi], "pool_size": len(p["issues"]),
            "eligible_count": len(eligible),
            "eligible_numbers": sorted(v["number"] for v in eligible),
            "clusters": clusters(eligible),
            "excluded_reasons": {r: sum(1 for v in p["verdicts"] if v["reason"] == r)
                                 for r in sorted({v["reason"] for v in p["verdicts"] if v["reason"]})},
        }
    return out


def main(argv: list[str]) -> int:
    action = argv[0] if argv else ""
    if action == "fetch":
        pool: dict = {"min_gap_days": MIN_GAP_DAYS, "repos": {}}
        cache: dict = {}
        for repo, (lo, hi) in TASK_WINDOWS.items():
            issues = fetch_repo(repo, lo, hi)
            for i in issues:
                for c in i["comments"]["nodes"]:
                    if c["authorAssociation"] in MAINTAINER:
                        for n in links_in(c["body"], repo):
                            if n < i["number"]:
                                info_of(repo, n, cache)
            linked_info = {k: v for k, v in cache.items() if k.startswith(repo + "#")}
            verdicts = [judge(i, repo, lo, linked_info) for i in issues]
            pool["repos"][repo] = {"window": [lo, hi], "issues": issues, "linked_info": linked_info,
                                   "verdicts": verdicts}
            print(f"{repo}: {len(issues)} closed items; "
                  f"{sum(v['eligible'] for v in verdicts)} eligible")
        (HERE / "pool.json").write_text(json.dumps(pool, indent=1, ensure_ascii=False) + "\n",
                                        encoding="utf-8")
        return 0
    if action == "draw":
        pool = json.loads((HERE / "pool.json").read_text(encoding="utf-8"))
        # Re-judge from the committed pool, so a change to the rule shows up as a changed draw.
        for repo, (lo, _) in TASK_WINDOWS.items():
            p = pool["repos"][repo]
            p["verdicts"] = [judge(i, repo, lo, p["linked_info"]) for i in p["issues"]]
        out = draw(pool)
        (HERE / "draw.json").write_text(json.dumps(out, indent=1) + "\n", encoding="utf-8")
        for repo, r in out["repos"].items():
            print(f"{repo}: eligible {r['eligible_count']} of {r['pool_size']}; "
                  f"{len(r['clusters'])} clusters: {[c['task_item'] for c in r['clusters']]}")
        return 0
    print(__doc__)
    return 2


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
